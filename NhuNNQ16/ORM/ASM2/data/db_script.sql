-- PostgreSQL database script for Movie Theater Application (movietheaterdb)

-- 1. Create database (uncomment if creating database from scratch)
-- CREATE DATABASE movietheaterdb;

-- 2. Create CINEMA_ROOM table
CREATE TABLE CINEMA_ROOM (
    CINEMA_ROOM_ID SERIAL PRIMARY KEY,
    CINEMA_ROOM_NAME VARCHAR(255) UNIQUE,
    SEAT_QUANTITY INT
);

-- 3. Create CINEMA_ROOM_DETAIL table (One-to-One with CINEMA_ROOM)
CREATE TABLE CINEMA_ROOM_DETAIL (
    CINEMA_ROOM_DETAIL_ID SERIAL PRIMARY KEY,
    CINEMA_ROOM_ID INT NOT NULL UNIQUE,
    ROOM_RATE INT,
    ACTIVE_DATE DATE,
    ROOM_DESCRIPTION VARCHAR(250),
    FOREIGN KEY (CINEMA_ROOM_ID) REFERENCES CINEMA_ROOM(CINEMA_ROOM_ID) ON DELETE CASCADE
);

-- 4. Create SEAT table (One-to-Many with CINEMA_ROOM)
CREATE TABLE SEAT (
    SEAT_ID SERIAL PRIMARY KEY,
    CINEMA_ROOM_ID INT NOT NULL,
    SEAT_COLUMN VARCHAR(255),
    SEAT_ROW INT,
    SEAT_STATUS VARCHAR(255),
    SEAT_TYPE VARCHAR(255),
    FOREIGN KEY (CINEMA_ROOM_ID) REFERENCES CINEMA_ROOM(CINEMA_ROOM_ID) ON DELETE CASCADE
);
